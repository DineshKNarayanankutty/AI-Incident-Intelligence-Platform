"""Build the fixed candidate evaluation dataset and the production baseline.

Deterministic: stratified 25% holdout of data/synthetic_incidents.csv,
random_state=42. Run it only when the reference dataset intentionally changes;
the outputs are committed and never regenerated by workflows.

  python -m scripts.build_candidate_evaluation
  python -m scripts.build_candidate_evaluation --baseline-output data/reference/production_model_metrics.json
  python -m scripts.build_candidate_evaluation --baseline-output ... --model path/to/model.joblib

Without --model the baseline is reproduced locally by fitting the production
pipeline configuration on the complementary 75% split. With --model (for
example the downloaded azureml:incident-severity:1 artifact) that exact model is
evaluated instead and recorded as the baseline source.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.data.generate_synthetic_data import FIELDNAMES, SEVERITIES
from src.training.evaluate import classification_metrics
from src.training.features import incident_text
from src.training.reference_split import RANDOM_STATE, TEST_SIZE, dataset_fingerprint, reference_split
from src.training.train import load_rows

DEFAULT_SOURCE = Path("data/synthetic_incidents.csv")
DEFAULT_OUTPUT = Path("data/reference/candidate_evaluation.csv")


def write_evaluation_csv(rows: list[dict[str, str]], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDNAMES, lineterminator="\n")
        writer.writeheader()
        writer.writerows({name: row[name] for name in FIELDNAMES} for row in rows)


def _fit_reference_model(train_rows: list[dict[str, str]]):
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import Pipeline

    model = Pipeline(
        steps=[
            ("tfidf", TfidfVectorizer(ngram_range=(1, 2), min_df=2, max_features=5000)),
            ("classifier", LogisticRegression(max_iter=1000, class_weight="balanced", random_state=RANDOM_STATE)),
        ]
    )
    model.fit([incident_text(r) for r in train_rows], [r["severity"] for r in train_rows])
    return model


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--baseline-output", type=Path, default=None)
    parser.add_argument("--model", type=Path, default=None, help="Optional model.joblib to use as the baseline.")
    parser.add_argument("--model-name", default="incident-severity")
    parser.add_argument("--model-version", default="1")
    args = parser.parse_args()

    train_rows, evaluation_rows = reference_split(load_rows(args.source))
    write_evaluation_csv(evaluation_rows, args.output)
    fingerprint = dataset_fingerprint(load_rows(args.output))
    print(f"Wrote {len(evaluation_rows)} rows to {args.output}\nfingerprint sha256: {fingerprint}")

    if args.baseline_output is None:
        return

    if args.model is not None:
        import joblib

        model = joblib.load(args.model)
        source = f"registered artifact evaluated from {args.model.name}"
    else:
        model = _fit_reference_model(train_rows)
        source = "reproduced locally: production pipeline configuration fitted on the complementary 75% split"

    predictions = model.predict([incident_text(r) for r in evaluation_rows]).tolist()
    metrics = classification_metrics([r["severity"] for r in evaluation_rows], predictions, SEVERITIES)
    baseline = {
        "model_name": args.model_name,
        "model_version": args.model_version,
        "accuracy": float(metrics["accuracy"]),
        "macro_f1": float(metrics["macro_f1"]),
        "evaluation_dataset": str(args.output).replace("\\", "/"),
        "evaluation_dataset_sha256": fingerprint,
        "evaluation_rows": len(evaluation_rows),
        "evaluation_test_size": TEST_SIZE,
        "evaluation_random_state": RANDOM_STATE,
        "baseline_source": source,
    }
    args.baseline_output.parent.mkdir(parents=True, exist_ok=True)
    args.baseline_output.write_text(json.dumps(baseline, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(baseline, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
